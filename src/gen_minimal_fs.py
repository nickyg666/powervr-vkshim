#!/usr/bin/env python3
"""Generate minimal fragment-shader SPIR-V blobs (1..8 colour outputs).

Used by the PowerVR compatibility shim as a last-resort replacement for a
fragment stage that the proprietary driver's SPIR-V front end refuses to
compile.  The blobs are produced with spirv-as so the binary encoding is
guaranteed correct.
"""
import os
import struct
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TMP = os.path.join(HERE, ".gen_tmp")

TEMPLATE = """               OpCapability Shader
               OpMemoryModel Logical GLSL450
               OpEntryPoint Fragment %main "main" {iface}
               OpExecutionMode %main OriginUpperLeft
{decs}       %void = OpTypeVoid
     %fnty = OpTypeFunction %void
    %float = OpTypeFloat 32
     %v4f  = OpTypeVector %float 4
   %ptrOut = OpTypePointer Output %v4f
{outs}     %c0  = OpConstant %float 0
     %cz  = OpConstantComposite %v4f %c0 %c0 %c0 %c0
    %main = OpFunction %void None %fnty
    %lbl  = OpLabel
{stores}           OpReturn
           OpFunctionEnd
"""


def build(n):
    iface = " ".join("%%out%d" % i for i in range(n))
    decs = "".join("               OpDecorate %%out%d Location %d\n" % (i, i) for i in range(n))
    outs = "".join("     %%out%d = OpVariable %%ptrOut Output\n" % i for i in range(n))
    stores = "".join("           OpStore %%out%d %%cz\n" % i for i in range(n))
    return TEMPLATE.format(iface=iface, decs=decs, outs=outs, stores=stores)


VERTEX_TEMPLATE = """               OpCapability Shader
               OpMemoryModel Logical GLSL450
               OpEntryPoint Vertex %main "main" %gl_Position
               OpDecorate %gl_Position BuiltIn Position
       %void = OpTypeVoid
     %fnty = OpTypeFunction %void
    %float = OpTypeFloat 32
     %v4f  = OpTypeVector %float 4
   %ptrOut = OpTypePointer Output %v4f
%gl_Position = OpVariable %ptrOut Output
     %c0  = OpConstant %float 0
     %cz  = OpConstantComposite %v4f %c0 %c0 %c0 %c0
    %main = OpFunction %void None %fnty
    %lbl  = OpLabel
           OpStore %gl_Position %cz
           OpReturn
           OpFunctionEnd
"""


def build_vs():
    return VERTEX_TEMPLATE


def main():
    os.makedirs(TMP, exist_ok=True)
    arrays = []
    for n in range(1, 9):
        asm = build(n)
        ap = os.path.join(TMP, "min%d.spvasm" % n)
        sp = os.path.join(TMP, "min%d.spv" % n)
        with open(ap, "w") as f:
            f.write(asm)
        subprocess.run(["spirv-as", "--target-env", "vulkan1.0", ap, "-o", sp], check=True)
        subprocess.run(["spirv-val", "--target-env", "vulkan1.0", sp], check=True)
        data = open(sp, "rb").read()
        words = struct.unpack("<%dI" % (len(data) // 4), data)
        arrays.append((n, words))

    # minimal vertex shader
    ap = os.path.join(TMP, "minvs.spvasm")
    sp = os.path.join(TMP, "minvs.spv")
    with open(ap, "w") as f:
        f.write(build_vs())
    subprocess.run(["spirv-as", "--target-env", "vulkan1.0", ap, "-o", sp], check=True)
    subprocess.run(["spirv-val", "--target-env", "vulkan1.0", sp], check=True)
    vsdata = open(sp, "rb").read()
    vswords = struct.unpack("<%dI" % (len(vsdata) // 4), vsdata)

    out = os.path.join(HERE, "minimal_fs.h")
    with open(out, "w") as f:
        f.write("/* generated by gen_minimal_fs.py - do not edit */\n")
        f.write("#ifndef MINIMAL_FS_H\n#define MINIMAL_FS_H\n#include <stddef.h>\n#include <stdint.h>\n\n")
        for n, words in arrays:
            f.write("static const uint32_t minimal_fs_%d[] = {\n" % n)
            for i in range(0, len(words), 6):
                chunk = ", ".join("0x%08xu" % w for w in words[i:i + 6])
                f.write("    %s,\n" % chunk)
            f.write("};\n\n")
        f.write("static const uint32_t minimal_vs[] = {\n")
        for i in range(0, len(vswords), 6):
            chunk = ", ".join("0x%08xu" % w for w in vswords[i:i + 6])
            f.write("    %s,\n" % chunk)
        f.write("};\n\n")
        f.write("static const uint32_t *minimal_fs_get(int n, size_t *count)\n{\n")
        f.write("    switch (n) {\n")
        for n, words in arrays:
            f.write("    case %d: *count = %d; return minimal_fs_%d;\n" % (n, len(words), n))
        f.write("    default: *count = 0; return 0;\n    }\n}\n\n")
        f.write("#endif\n")
    print("wrote", out)
    for n, words in arrays:
        print("  n_out=%d words=%d" % (n, len(words)))


if __name__ == "__main__":
    main()
